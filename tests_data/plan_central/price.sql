CREATE TABLE `price` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `organization_code` varchar(50) COLLATE utf8mb4_unicode_ci NOT NULL,
  `code` varchar(120) COLLATE utf8mb4_unicode_ci NOT NULL,
  `name` varchar(255) COLLATE utf8mb4_unicode_ci NOT NULL,
  `price_type` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL,
  `data_origin` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL,
  `product_id` bigint NOT NULL,
  `amount` decimal(18,6) NOT NULL,
  `currency` varchar(3) COLLATE utf8mb4_unicode_ci NOT NULL,
  `sales_channel_id` bigint DEFAULT NULL,
  `customer_id` bigint DEFAULT NULL,
  `node_id` bigint DEFAULT NULL,
  `surplus_sale_id` bigint DEFAULT NULL,
  `customer_contract_item_id` bigint DEFAULT NULL,
  `basis` varchar(10) COLLATE utf8mb4_unicode_ci NOT NULL,
  `pricing_quantity` decimal(18,9) NOT NULL,
  `reason` varchar(150) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `valid_from` date NOT NULL,
  `valid_to` date DEFAULT NULL,
  `active` bit(1) NOT NULL,
  `created_date` datetime(6) NOT NULL,
  `created_by` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL,
  `last_modified_date` datetime(6) NOT NULL,
  `last_modified_by` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_price_code` (`organization_code`,`code`),
  KEY `fk_price_product` (`product_id`),
  KEY `fk_price_customer` (`customer_id`),
  KEY `fk_price_node` (`node_id`),
  KEY `fk_price_customer_contract_item` (`customer_contract_item_id`),
  KEY `fk_price_surplus_sale` (`surplus_sale_id`),
  KEY `fk_price_sales_channel` (`sales_channel_id`),
  CONSTRAINT `fk_price_customer` FOREIGN KEY (`customer_id`) REFERENCES `party` (`id`),
  CONSTRAINT `fk_price_customer_contract_item` FOREIGN KEY (`customer_contract_item_id`) REFERENCES `customer_contract_item` (`id`),
  CONSTRAINT `fk_price_node` FOREIGN KEY (`node_id`) REFERENCES `network_node` (`id`),
  CONSTRAINT `fk_price_product` FOREIGN KEY (`product_id`) REFERENCES `planning_product` (`id`),
  CONSTRAINT `fk_price_sales_channel` FOREIGN KEY (`sales_channel_id`) REFERENCES `sales_channel` (`id`),
  CONSTRAINT `fk_price_surplus_sale` FOREIGN KEY (`surplus_sale_id`) REFERENCES `surplus_sale` (`id`),
  CONSTRAINT `ck_price_amount` CHECK (((`amount` >= 0) and (`pricing_quantity` > 0))),
  CONSTRAINT `ck_price_reason` CHECK ((((`price_type` = _utf8mb4'MARKET') and (`customer_id` is null) and (`reason` is not null) and (trim(`reason`) <> _utf8mb4'')) or (((`price_type` <> _utf8mb4'MARKET') or (`customer_id` is not null)) and (`reason` is null)))),
  CONSTRAINT `ck_price_validity` CHECK (((`valid_to` is null) or (`valid_to` >= `valid_from`)))
) ENGINE=InnoDB AUTO_INCREMENT=30 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
