CREATE TABLE `disassembly_program` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `organization_code` varchar(50) COLLATE utf8mb4_unicode_ci NOT NULL,
  `code` varchar(50) COLLATE utf8mb4_unicode_ci NOT NULL,
  `name` varchar(150) COLLATE utf8mb4_unicode_ci NOT NULL,
  `production_stream_id` bigint NOT NULL,
  `input_product_id` bigint NOT NULL,
  `transformation_definition_id` bigint NOT NULL COMMENT 'The disassembly recipe that splits the input.',
  `valid_from` date NOT NULL,
  `valid_to` date DEFAULT NULL COMMENT 'The last day, included; null = open-ended.',
  `input_weight_from_kg` decimal(18,6) DEFAULT NULL COMMENT 'Least weight of one input item, included; null = any weight (the input''s own weight, not live weight).',
  `input_weight_to_kg_exclusive` decimal(18,6) DEFAULT NULL COMMENT 'Weight of one input item the program stops at, excluded; null = any weight.',
  `min_share_percent` decimal(9,4) DEFAULT NULL COMMENT 'Least share of the eligible input; null = not stated.',
  `max_share_percent` decimal(9,4) DEFAULT NULL COMMENT 'Most share of the eligible input; null = not stated.',
  `preference_rank` int DEFAULT NULL COMMENT 'Preference among programs, 1 first; null = no preference (the solver chooses freely). Not rank: a reserved word in MySQL 8.',
  `active` bit(1) NOT NULL,
  `created_date` datetime(6) NOT NULL,
  `created_by` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL,
  `last_modified_date` datetime(6) NOT NULL,
  `last_modified_by` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_disassembly_program_code` (`organization_code`,`code`),
  KEY `fk_disassembly_program_stream` (`production_stream_id`),
  KEY `fk_disassembly_program_input_product` (`input_product_id`),
  KEY `fk_disassembly_program_recipe` (`transformation_definition_id`),
  CONSTRAINT `fk_disassembly_program_input_product` FOREIGN KEY (`input_product_id`) REFERENCES `planning_product` (`id`),
  CONSTRAINT `fk_disassembly_program_recipe` FOREIGN KEY (`transformation_definition_id`) REFERENCES `transformation_definition` (`id`),
  CONSTRAINT `fk_disassembly_program_stream` FOREIGN KEY (`production_stream_id`) REFERENCES `production_stream` (`id`),
  CONSTRAINT `ck_disassembly_program_rank` CHECK (((`preference_rank` is null) or (`preference_rank` > 0))),
  CONSTRAINT `ck_disassembly_program_share` CHECK ((((`min_share_percent` is null) or (`min_share_percent` between 0 and 100)) and ((`max_share_percent` is null) or (`max_share_percent` between 0 and 100)) and ((`min_share_percent` is null) or (`max_share_percent` is null) or (`min_share_percent` <= `max_share_percent`)))),
  CONSTRAINT `ck_disassembly_program_weight` CHECK ((((`input_weight_from_kg` is null) or (`input_weight_from_kg` >= 0)) and ((`input_weight_to_kg_exclusive` is null) or (`input_weight_from_kg` is null) or (`input_weight_to_kg_exclusive` > `input_weight_from_kg`)) and ((`input_weight_to_kg_exclusive` is null) or (`input_weight_to_kg_exclusive` > 0)))),
  CONSTRAINT `ck_disassembly_program_window` CHECK (((`valid_to` is null) or (`valid_to` >= `valid_from`)))
) ENGINE=InnoDB AUTO_INCREMENT=2 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Which disassembly recipe splits which input, for which weights or grades, at which sites and when (captured, not planned).'
