CREATE TABLE `opening_make_order` (
  `id` bigint NOT NULL,
  `opening_position_snapshot_id` bigint NOT NULL,
  `code` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'The order reference.',
  `network_node_id` bigint DEFAULT NULL COMMENT 'Our site it runs at; null on a toll order, whose partner runs it',
  `transformation_definition_id` bigint DEFAULT NULL COMMENT 'The recipe version it runs; null on a toll order, whose line names it',
  `supply_agreement_item_id` bigint DEFAULT NULL COMMENT 'The toll line it is open on; null on an order at our own site',
  `output_product_id` bigint NOT NULL,
  `planned_output_quantity` decimal(18,6) NOT NULL COMMENT 'In the output product''s unit.',
  `completed_output_quantity` decimal(18,6) DEFAULT NULL COMMENT 'In the output product''s unit; null = not stated',
  `planned_start_on` date NOT NULL,
  `planned_finish_on` date NOT NULL,
  `firm` bit(1) NOT NULL,
  `started_on` date DEFAULT NULL COMMENT 'Stated once it has begun.',
  `processing_route_id` bigint DEFAULT NULL COMMENT 'null = core finds the step',
  `operation_sequence` int DEFAULT NULL,
  `capacity_id` bigint DEFAULT NULL COMMENT 'null = core finds the resource',
  `entry_origin` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'IMPORTED or HAND_ENTERED, set by core (E-251)',
  `checked_on_as_of` date DEFAULT NULL COMMENT 'the position''s as-of when a person last saved or confirmed this hand-entered row; null on an imported one, and on a hand-entered one saved before the position had a day (E-251)',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_opening_make_order_code` (`opening_position_snapshot_id`,`code`),
  KEY `fk_opening_make_order_node` (`network_node_id`),
  KEY `fk_opening_make_order_recipe` (`transformation_definition_id`),
  KEY `fk_opening_make_order_output` (`output_product_id`),
  KEY `fk_opening_make_order_toll_line` (`supply_agreement_item_id`),
  KEY `fk_opening_make_order_route` (`processing_route_id`),
  KEY `fk_opening_make_order_capacity` (`capacity_id`),
  CONSTRAINT `fk_opening_make_order_capacity` FOREIGN KEY (`capacity_id`) REFERENCES `capacity` (`id`),
  CONSTRAINT `fk_opening_make_order_node` FOREIGN KEY (`network_node_id`) REFERENCES `network_node` (`id`),
  CONSTRAINT `fk_opening_make_order_output` FOREIGN KEY (`output_product_id`) REFERENCES `planning_product` (`id`),
  CONSTRAINT `fk_opening_make_order_recipe` FOREIGN KEY (`transformation_definition_id`) REFERENCES `transformation_definition` (`id`),
  CONSTRAINT `fk_opening_make_order_route` FOREIGN KEY (`processing_route_id`) REFERENCES `processing_route` (`id`),
  CONSTRAINT `fk_opening_make_order_snapshot` FOREIGN KEY (`opening_position_snapshot_id`) REFERENCES `opening_position_snapshot` (`id`),
  CONSTRAINT `fk_opening_make_order_toll_line` FOREIGN KEY (`supply_agreement_item_id`) REFERENCES `supply_agreement_item` (`id`),
  CONSTRAINT `ck_opening_make_order_dates` CHECK ((`planned_finish_on` >= `planned_start_on`)),
  CONSTRAINT `ck_opening_make_order_entry_origin` CHECK (((`entry_origin` in (_utf8mb4'IMPORTED',_utf8mb4'HAND_ENTERED')) and ((`entry_origin` = _utf8mb4'HAND_ENTERED') or (`checked_on_as_of` is null)))),
  CONSTRAINT `ck_opening_make_order_quantities` CHECK (((`planned_output_quantity` > 0) and ((`completed_output_quantity` is null) or (`completed_output_quantity` >= 0)))),
  CONSTRAINT `ck_opening_make_order_runs` CHECK ((((`supply_agreement_item_id` is null) and (`network_node_id` is not null) and (`transformation_definition_id` is not null)) or ((`supply_agreement_item_id` is not null) and (`network_node_id` is null) and (`transformation_definition_id` is null) and (`processing_route_id` is null) and (`capacity_id` is null)))),
  CONSTRAINT `ck_opening_make_order_status` CHECK ((((`started_on` is null) or (`firm` = 1)) and ((`started_on` is not null) or (`completed_output_quantity` is null) or (`completed_output_quantity` = 0)))),
  CONSTRAINT `ck_opening_make_order_step` CHECK (((`processing_route_id` is null) = (`operation_sequence` is null)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='An open make order (released or in progress) at the opening position''s cut-off.'
