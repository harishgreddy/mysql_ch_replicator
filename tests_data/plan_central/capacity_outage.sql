CREATE TABLE `capacity_outage` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `organization_code` varchar(50) COLLATE utf8mb4_unicode_ci NOT NULL,
  `name` varchar(150) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'A label; the outage is known by its resource and start.',
  `capacity_id` bigint NOT NULL,
  `reason` varchar(150) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Why the resource stops, in the organisation''s own words; free text, the plan reads none (F72); null = not stated.',
  `from_time` time NOT NULL DEFAULT '00:00:00',
  `to_time` time DEFAULT NULL,
  `recurrence_until` date DEFAULT NULL,
  `availability_factor` decimal(19,6) NOT NULL COMMENT 'Share of the resource still usable during the outage (0 = fully out, 1 = fully usable); required, no default (D-177).',
  `from_date` date NOT NULL,
  `to_date` date NOT NULL,
  `recurrence_frequency` varchar(30) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'ONE_OFF',
  `created_date` datetime(6) NOT NULL,
  `created_by` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL,
  `last_modified_date` datetime(6) NOT NULL,
  `last_modified_by` varchar(100) COLLATE utf8mb4_unicode_ci NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_capacity_outage_start` (`organization_code`,`capacity_id`,`from_date`,`from_time`),
  KEY `fk_capacity_outage_capacity` (`capacity_id`),
  CONSTRAINT `fk_capacity_outage_capacity` FOREIGN KEY (`capacity_id`) REFERENCES `capacity` (`id`),
  CONSTRAINT `ck_capacity_outage_availability` CHECK (((`availability_factor` >= 0) and (`availability_factor` <= 1))),
  CONSTRAINT `ck_capacity_outage_recurrence` CHECK (((`recurrence_until` is null) or (`recurrence_frequency` <> _utf8mb4'ONE_OFF'))),
  CONSTRAINT `ck_capacity_outage_window` CHECK ((`to_date` >= `from_date`))
) ENGINE=InnoDB AUTO_INCREMENT=2 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
